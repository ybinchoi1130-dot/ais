import pandas as pd

data = {
    '이름': ['철수', '영희'],
    '국어': [90, 80],
    '수학': [85, 95],
    '영어': [70, 88],
    '비고': ['우수', '보통']
}

df = pd.DataFrame(data)
print(df)

#%%

"""
   이름  국어  수학  영어  비고
0  철수  90  85  70  우수
1  영희  80  95  88  보통
"""

#%%

# value_vars 없이 전체 변환할 때
# id_vars에 포함되지 않은 '국어', '수학', '영어', '비고'가 전부 풀려서 행으로 들어갑니다.

pd.melt(df, id_vars=['이름'])

df.melt(id_vars='이름')

#%%

"""
   이름 variable value
0  철수       국어    90
1  영희       국어    80
2  철수       수학    85
3  영희       수학    95
4  철수       영어    70
5  영희       영어    88
6  철수       비고    우수
7  영희       비고    보통
"""

#%%

# value_vars를 사용하여 특정 열만 변환할 때
# 점수 열('국어', '수학')만 선택하고 '영어'와 '비고'는 결과에서 제외합니다.

pd.melt(
    df,
    id_vars=['이름'],
    value_vars=['국어', '수학'],
    var_name='과목',
    value_name='점수'
)

#%%

"""
   이름  과목  점수
0  철수  국어  90
1  영희  국어  80
2  철수  수학  85
3  영희  수학  95
"""
